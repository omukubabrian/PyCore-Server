# POST: Create a new student

@app.route("/api/students", methods=["POST"])
def create_students():
    # Read the incoming JSON request body
    data = request.get_json(silent=True)

    # Reject requests without a valid JSON object
    if not isinstance(data, dict):
        return jsonify({
            "error": "Request body must be a JSON object."
        }), 400

    # Read and validate the required fields
    name = data.get("name")
    course = data.get("course")

    if not isinstance(name, str) or not name.strip():
        return jsonify({
            "error": "A non-empty name is required."
        }), 400

    if not isinstance(course, str) or not course.strip():
        return jsonify({
            "error": "A non-empty course is required."
        }), 400

    connection = None
    cursor = None

    try:
        # Connect to MySQL
        connection = get_db_connection()
        cursor = connection.cursor()

        # Insert the student into the database
        cursor.execute(
            "INSERT INTO students (name, course) VALUES (%s, %s)",
            (name.strip(), course.strip())
        )

        # Save the transaction
        connection.commit()

        # Get the ID generated by MySQL
        student = {
            "id": cursor.lastrowid,
            "name": name.strip(),
            "course": course.strip()
        }

        # Return the created record
        return jsonify({
            "message": "Student created successfully.",
            "student": student
        }), 201

    except Exception:
        # Undo any uncommitted database changes
        if connection is not None and connection.is_connected():
            connection.rollback()

        app.logger.exception("Failed to create student in MySQL")

        return jsonify({
            "error": "Could not create student."
        }), 500

    finally:
        # Release database resources
        if cursor is not None:
            cursor.close()

        if connection is not None and connection.is_connected():
            connection.close()



